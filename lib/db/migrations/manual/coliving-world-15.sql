-- ============================================================================
-- 合租房世界模型 · 第十五批：把「在等谁、等什么、等多久」变成结构化数据
--
-- 起因（2026-09-05 用户）：用户指出现在的消息层"太像社交软件发个消息而已，
-- 看上去只管发到消息就行"，要求参考特种兵电台、民航塔台、顶尖军事小队、
-- 激烈电竞指挥、敏捷站会那种协作密度来改造——"想象成一套房里每个人在对着
-- 手机打字实现激烈的公司开会，新时代的公司异步开会"。
--
-- 先立一条边界，**不能照搬**：军事/塔台/电竞的核心是「全员共享态势」，
-- 而这个项目的宪法第十条明令「把每个人的事留在他自己那儿」——
-- 谁投诉了谁、谁欠了租，都不能广播。所以可迁移的是**协作机制**
-- （闭环、阻塞暴露、角色化报文），不是信息广播。
--
-- 那几个领域真正共同、且这里缺的内核只有一个：**闭环**。
--   · 塔台：指令 → 复诵 readback → 确认 hearback，环不闭就一直追
--   · 军事小队：每条命令都知道在等谁回 "copy"
--   · 敏捷站会：blocker 必须当众暴露，不能烂在某个人手里
--   · 电竞指挥：喊了信号就盯着队友有没有响应，没响应立刻补位
-- 共同点是：**发出去只是一半，另一半是"有没有回来"，而且系统自己盯着。**
--
-- 对照现状：`communication.responded_at` / `response_message_id`
-- 第八批就加了，代码也会自动关联（收到入站消息时回填到最近一条待回应的
-- 沟通上）——**闭环的"记录"这一半已经有了**。缺的是另外三件：
--
--   1. **不是每条消息都需要回应**。"你的时段定在18-19点"是通知，
--      对方不回很正常；"你几点做饭？"不回就是卡住了。现在两者
--      在库里长得一模一样，`responded_at is null` 分不出
--      "还没回"和"根本不用回"，于是**没法判断哪件事真的卡住了**。
--   2. **没有等待时限**。等一小时和等三天，处理方式完全不同，
--      但库里只有 sent_at，"等多久算久"每次都要模型现算。
--   3. **没有按事情聚合的阻塞视图**。`pendingCommunication` 是按人查的
--      （"这个人有没有待回应的消息"），回答不了敏捷站会那个核心问题：
--      **"厨房排班这件事，现在到底卡在谁身上、卡了多久"**。
--
-- 这三件正是这两天反复出的 bug 的同源病根：AI 说"回头跟他们商量"然后
-- 就没有下文、反复问同一个人、忘了谁还没回话——因为它**从来没有一份
-- "我在等谁"的清单**，全靠每轮重读聊天记录临时拼。
--
-- 这批补的就是这份清单。
-- ============================================================================

alter table coliving.communication
  -- 这条消息是什么言语行为。**不是给人看的措辞分类，是给系统判断
  -- "要不要盯着回音"用的**：ask 必须有人回，inform 不用。
  --   ask     = 在问他一个问题，需要他回答
  --   inform  = 告知/通知，不需要他做什么
  --   propose = 提一个方案征求意见（共同生活的规则类，宪法第六条）
  --   confirm = 复述并请他确认（塔台的 readback，事关钱/时间/权利时用）
  --   remind  = 之前说过的事再提一次
  --   escalate= 转给房东/外部
  add column if not exists act text
    check (act in ('ask', 'inform', 'propose', 'confirm', 'remind', 'escalate')),
  -- **这条发出去之后，要不要盯着对方回音。** 默认 false（保守）：
  -- 宁可漏盯，也不要把一堆根本不用回的通知算成"卡住了"，
  -- 那样阻塞清单会被噪音淹没，等于没有。
  add column if not exists expects_reply boolean not null default false,
  -- 期望什么时候之前有回音。**不让模型填具体时间**（它会乱填），
  -- 由代码按 act 推：ask/confirm → 24h，remind → 12h，其余 null。
  -- 超过这个点还没 responded_at，就是"等超时了"，进阻塞清单的醒目位置。
  add column if not exists reply_due_at timestamptz;

comment on column coliving.communication.expects_reply is
  '这条发出去之后要不要盯着回音。**默认 false**——不需要回复的通知
   如果也算进"在等回复"，阻塞清单会被噪音淹没。
   只有真的在问对方、或请对方确认时才是 true';

comment on column coliving.communication.reply_due_at is
  '期望回音的时限，由代码按 act 推出来，不由模型填。
   超时且仍无 responded_at = 这件事卡住了，需要主动跟进';

-- 阻塞清单的查询模式：这栋房子里，所有"发出去了、等着回、还没回"的沟通，
-- 按等待时间排序。**部分索引**只覆盖真正在等的那些，表再大也不影响。
create index if not exists communication_blocked_idx
  on coliving.communication (household_id, reply_due_at)
  where status = 'sent' and expects_reply = true and responded_at is null;
