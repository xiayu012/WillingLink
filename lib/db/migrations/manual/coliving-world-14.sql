-- ============================================================================
-- 合租房世界模型 · 第十四批：记忆要分得清「他自己说的」和「别人说他的」
--
-- 起因（2026-09-05 用户）：用户拿来一份外部的架构参考文字，其中一条
-- 直接点中了这个项目的真实缺口：
--
--   > 必须区分「确认的事实」和「某个人的陈述」。
--   > 例如 A 说"B 每天晚上都很吵"，不能直接记录成"B 每天晚上都很吵"
--   > 这一事实，而应该保留这是 A 的陈述、来源以及必要的不确定性。
--
-- 对照现状：`memory.basis` 已经有 stated/observed/inferred 三个值
-- （第七批加的，防的是"AI 把自己的推测当事实读回去"），这一层做得很好。
-- **但这三个值覆盖不了合租场景里最常见、也最危险的那一类**：
-- 一方投诉另一方。
--
--   A 说"B 半夜在厨房打电话吵到我"，模型要给 B 记一条 memory：
--     · stated？ 定义是"当事人自己说的"——这条不是 B 说的
--     · observed？AI 没有身体、没在现场，看不到
--     · inferred？也不对，这不是推断出来的，是转述
--   三个都不贴，模型最可能填 stated（因为"确实有人说了"）——
--   于是 **B 的长期档案里留下一条读起来像已确认事实的记录**，
--   几个月后没人记得这只是 A 的单方说法。
--
-- 而且 `stated_by`（谁说的）这个字段第七批就加了，但 `getMembers` 渲染
-- 住户档案时**只输出 content、只给 inferred 加"（推测）"前缀**，
-- stated_by 从来没被用过——**数据存下来了，模型却看不到**。
--
-- 这跟宪法第九条（一方的说法不是事实，处置前须听取另一方）、
-- rubric 第9条（只听了一边就下结论了吗）是同一件事，只是那两处是
-- 靠提示词每轮提醒模型自觉，数据层面没有任何结构支撑。
--
-- 修法（最小改动，不动已有语义）：
--   1. basis 增加第四个值 third_party = 别人说他的，当事人还没确认
--   2. 渲染时把 stated_by 的名字带出来（在 repo.getMembers 里改）
-- ============================================================================

alter table coliving.memory
  drop constraint if exists memory_basis_check;

alter table coliving.memory
  add constraint memory_basis_check
    check (basis in ('stated', 'observed', 'inferred', 'third_party'));

comment on column coliving.memory.basis is
  'stated=当事人自己说的（可当事实用）· observed=系统观察到的 ·
   inferred=**你推出来的，不是事实** ·
   third_party=**别人说他的，当事人没确认过**（A 投诉 B 那类）。
   混淆这四者会让记忆被猜测和单方指控污染';
