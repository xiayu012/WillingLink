-- 合租房世界模型 · 第十三批：case_position 允许没有 case_id
--
-- 起因（2026-09-04 用户）：真实使用场景，房东在案子还没开出来之前
-- 随口说了一句"七点用厨房最合适"——这时候还没有冲突浮现，模型判断
-- 这只是随口一提，没有 openCase。但 recordPosition 工具当时要求
-- 必须绑定一个已存在的 caseId，这句偏好就没有被结构化记住，只能靠
-- recentOutbound 的 12 条滚动窗口纯文字流水账。等到几轮之后真的排班
-- 冲突浮现、案子被开出来时，这条窗口早就被后续消息挤掉了，模型看不到
-- 房东说过的偏好，于是又对着房东说"你的时间还没确认"——这句话本身
-- 是错的，房东其实早说过了。
--
-- 修法：case_id 允许为 null。null 代表"这是一条独立于任何具体案子的
-- 表态"（比如日常提到的时段偏好），跟 case_position 现有语义
-- （谁、对什么事、说了什么）完全兼容，只是不强求这句话此刻已经跟
-- 一件"未结的事"绑在一起。等案子真的开出来后，可以把之前记的
-- 独立表态用 person_id 查出来、供模型参考，不需要事先预判"这句话
-- 以后会不会变成一个案子"。
-- ============================================================================

alter table coliving.case_position
  alter column case_id drop not null;
